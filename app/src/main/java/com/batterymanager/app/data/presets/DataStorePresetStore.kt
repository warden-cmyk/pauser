package com.batterymanager.app.data.presets

import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringSetPreferencesKey
import kotlinx.coroutines.flow.first

/**
 * [PresetStore] backed by Jetpack Preferences DataStore.
 *
 * Presets are more structured than the single `Set<String>` selection
 * from Session 6 (each preset has an id, a name, and its own
 * package-name set), and the Architecture doc's Component 5/6 guidance
 * describes presets as Room-backed relational data. This session does
 * not introduce Room, deliberately: no other Room entity (run history,
 * app cache) exists anywhere in this codebase yet, and this container
 * cannot run a real Gradle build to verify a first-time
 * Room/KSP-or-kapt setup actually resolves (same constraint every prior
 * session has hit - see PROJECT_STATE.md). Hand-encoding this specific,
 * small, fixed shape into the same Preferences-DataStore mechanism
 * Session 6 already established was judged the lower-risk choice for
 * *this* session. Introducing Room once run history/app cache also need
 * it (see PROJECT_STATE.md's next-step note) is the natural point to
 * replace this with the Architecture doc's intended design.
 *
 * Each preset is encoded as one string -
 * `id` + [FIELD_SEPARATOR] + `name` + [FIELD_SEPARATOR] + package names
 * joined by [PACKAGE_SEPARATOR] - and the whole set of encoded strings is
 * stored under one `stringSetPreferencesKey`, mirroring
 * [com.batterymanager.app.data.selection.DataStoreSelectionStore]'s
 * single-key approach. [FIELD_SEPARATOR] (U+001F, unit separator) and
 * [PACKAGE_SEPARATOR] (U+001E, record separator) are non-printable
 * control characters not producible from a normal keyboard, so they are
 * safe delimiters for user-typed preset names; package names are
 * dot-separated Java identifiers and cannot contain them either. A
 * preset's id is a UUID generated by [DefaultPresetRepository], so two
 * distinct presets can never encode to the same string and collide as
 * `Set<String>` entries.
 *
 * A stored string that fails to decode (wrong shape, e.g. hand-edited or
 * corrupted) is dropped rather than crashing the read - the same
 * "corrupt persisted data becomes empty for that entry, not a thrown
 * failure" philosophy already used for the selection store's corrupt-file
 * case (see `MainViewModel.restoreSelection`).
 */
class DataStorePresetStore(
    private val dataStore: DataStore<Preferences>
) : PresetStore {

    override suspend fun getPresets(): List<Preset> =
        (dataStore.data.first()[PRESETS_KEY] ?: emptySet())
            .mapNotNull(::decodePreset)

    override suspend fun savePresets(presets: List<Preset>) {
        dataStore.edit { preferences ->
            preferences[PRESETS_KEY] = presets.map(::encodePreset).toSet()
        }
    }

    private companion object {
        val PRESETS_KEY = stringSetPreferencesKey("saved_presets")

        const val FIELD_SEPARATOR = "\u001F"
        const val PACKAGE_SEPARATOR = "\u001E"

        fun encodePreset(preset: Preset): String =
            listOf(
                preset.id,
                preset.name,
                preset.packageNames.joinToString(PACKAGE_SEPARATOR)
            ).joinToString(FIELD_SEPARATOR)

        fun decodePreset(raw: String): Preset? {
            val parts = raw.split(FIELD_SEPARATOR)
            if (parts.size != 3) return null
            val (id, name, packagesJoined) = parts
            if (id.isEmpty() || name.isEmpty()) return null
            val packageNames = if (packagesJoined.isEmpty()) {
                emptySet()
            } else {
                packagesJoined.split(PACKAGE_SEPARATOR).toSet()
            }
            return Preset(id = id, name = name, packageNames = packageNames)
        }
    }
}
